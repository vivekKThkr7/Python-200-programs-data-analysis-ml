# List vs Tuple vs Set

list_data = [10, 20, 30, 40, 50, 60]
tuple_date = (10, 20, 30, 40, 50, 60)
set_date = {10, 20, 30, 40, 50, 60}
print(list_data)
print(tuple_date)
print(set_date)




# List
# [10, 20, 20, 30]
# → ordered collection
# → duplicates allowed
# → changeable

# Tuple
# (10, 20, 20, 30)
# → ordered collection
# → duplicates allowed
# → not changeable

# Set
# {10, 20, 30}
# → unique values
# → duplicates removed