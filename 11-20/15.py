# Type conversion ;  change from one datatype to another datatype

age = "27"
print(age)
print(type(age))  # <class 'str'>


age = int(age)
print(age)
print(type(age))   # <class 'int'


number = int("100")
print(number)
print(type(number))   # int 

price = float("99.98")
print(price)
print(type(price))

age = str(27)
print(age)
print(type(age))
