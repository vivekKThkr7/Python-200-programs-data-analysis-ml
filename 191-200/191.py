# NumPy Arrays

# NumPy stands for Numerical Python. It is a library used for numerical computing, especially when working with many numbers.

# when we're analysing numerical data, NumPy arrays provide convenient element-by-element mathematical operations.

import numpy as np

numbers = np.array([10, 20, 30, 40])

print("Original array:", numbers)
print("Add 5:", numbers + 5)
print("Multiply by 2:", numbers * 2)
print("First value:", numbers[0])