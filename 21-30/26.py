# Grade calculator

marks = float(input("Enter your marks: "))

if marks >=90:
    print("Grade: A+")

elif  marks >=80:
    print("Grade: A")

elif marks >=70:
    print("Grade: B+")

elif marks >=60: 
    print("grade: B")

elif marks >= 40:
    print("Grade: D")

else:
    print("Non Grade")
    